-- Unified, metadata-only email delivery log for the Resend API path.
-- Authentication emails remain managed by Supabase Auth over custom SMTP.

begin;

create table if not exists public.email_delivery_logs (
  id bigint generated by default as identity primary key,
  event_key text not null,
  category text not null check (category in (
    'admin_broadcast',
    'maintenance_recovery',
    'support_feedback',
    'security_notice',
    'friend_notification',
    'product_update',
    'system_notice'
  )),
  source text not null check (source in (
    'admin-bulk-email',
    'maintenance-notify',
    'dev-feedback'
  )),
  actor_id uuid references auth.users(id) on delete set null,
  recipient_user_id uuid references auth.users(id) on delete set null,
  reference_id text,
  provider text not null default 'resend' check (provider = 'resend'),
  provider_message_id text,
  status text not null default 'pending' check (status in (
    'pending', 'accepted', 'failed', 'delivered', 'bounced', 'complained'
  )),
  attempt_count integer not null default 1 check (attempt_count >= 1),
  error_code text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint email_delivery_logs_event_key_length check (char_length(event_key) between 1 and 256),
  constraint email_delivery_logs_reference_length check (reference_id is null or char_length(reference_id) <= 128)
);

create unique index if not exists email_delivery_logs_event_key_uidx
  on public.email_delivery_logs(event_key);
create index if not exists email_delivery_logs_created_at_idx
  on public.email_delivery_logs(created_at desc);
create index if not exists email_delivery_logs_provider_message_idx
  on public.email_delivery_logs(provider_message_id)
  where provider_message_id is not null;
create index if not exists email_delivery_logs_status_created_idx
  on public.email_delivery_logs(status, created_at desc);

alter table public.email_delivery_logs enable row level security;
revoke all on table public.email_delivery_logs from public, anon, authenticated;
grant all on table public.email_delivery_logs to service_role;
grant usage, select on sequence public.email_delivery_logs_id_seq to service_role;

comment on table public.email_delivery_logs is
  'Metadata-only audit trail for application email sends. Recipient addresses and message bodies are intentionally not stored.';

commit;
