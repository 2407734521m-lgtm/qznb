create or replace function public.snapshot_admin_broadcast_recipients()
returns trigger language plpgsql security definer set search_path = ''
as $function$
begin
  insert into public.broadcast_deliveries (broadcast_id, user_id)
  select new.id, p.id
    from public.profiles p
   where p.joined = true
     and (
       (p.role = 'member' and (
         new.audience = 'all'
         or (new.audience = 'app' and exists (select 1 from public.member_presence mp where mp.profile_id = p.id and mp.client_platform = 'mobile'))
         or (new.audience = 'web' and exists (select 1 from public.member_presence mp where mp.profile_id = p.id and mp.client_platform = 'web'))
       ))
       or (p.role in ('member','admin') and new.audience = 'selected' and new.target_ids ? p.id::text)
     )
  on conflict (broadcast_id, user_id) do nothing;
  return new;
end;
$function$;
revoke all on function public.snapshot_admin_broadcast_recipients() from public, anon, authenticated;
drop trigger if exists snapshot_admin_broadcast_recipients on public.admin_broadcasts;
create trigger snapshot_admin_broadcast_recipients
  after insert on public.admin_broadcasts
  for each row execute function public.snapshot_admin_broadcast_recipients();

insert into public.broadcast_deliveries (broadcast_id, user_id, first_viewed_at, last_viewed_at, view_count, dismissed_at)
select b.id, p.id, r.updated_at, r.updated_at,
       case when r.broadcast_id is not null then 1 else 0 end::smallint,
       case when r.broadcast_id is not null then r.updated_at else null end
  from public.admin_broadcasts b
  cross join public.profiles p
  left join public.broadcast_receipts r on r.broadcast_id = b.id and r.user_id = p.id
 where p.joined = true and p.role = 'member'
   and (
     b.audience = 'all'
     or (b.audience = 'app' and exists (select 1 from public.member_presence mp where mp.profile_id = p.id and mp.client_platform = 'mobile'))
     or (b.audience = 'web' and exists (select 1 from public.member_presence mp where mp.profile_id = p.id and mp.client_platform = 'web'))
     or (b.audience = 'selected' and b.target_ids ? p.id::text)
   )
on conflict (broadcast_id, user_id) do nothing;

create or replace function public.record_broadcast_delivery_event(p_broadcast_id bigint, p_event text)
returns boolean language plpgsql security definer set search_path = ''
as $function$
declare
  v_now timestamptz := pg_catalog.now();
  v_delivery public.broadcast_deliveries%rowtype;
  v_broadcast public.admin_broadcasts%rowtype;
begin
  if auth.uid() is null then raise exception 'authentication required' using errcode = '42501'; end if;
  if coalesce(p_event, '') not in ('view','click','dismiss') then raise exception 'invalid delivery event' using errcode = '22023'; end if;
  select d.* into v_delivery from public.broadcast_deliveries d
   where d.broadcast_id = p_broadcast_id and d.user_id = auth.uid() for update;
  if not found then return false; end if;
  select b.* into v_broadcast from public.admin_broadcasts b
   where b.id = p_broadcast_id and b.revoked = false
     and (b.starts_at is null or b.starts_at <= v_now)
     and (b.expires_at is null or b.expires_at > v_now);
  if not found then return false; end if;
  if p_event = 'view' then
    if v_delivery.view_count >= v_broadcast.max_impressions then return false; end if;
    if v_delivery.last_viewed_at is not null
       and v_delivery.last_viewed_at > v_now - pg_catalog.make_interval(hours => v_broadcast.repeat_interval_hours) then return false; end if;
    update public.broadcast_deliveries
       set first_viewed_at = coalesce(first_viewed_at, v_now), last_viewed_at = v_now,
           view_count = least(view_count + 1, 5)
     where broadcast_id = p_broadcast_id and user_id = auth.uid();
  elsif p_event = 'click' then
    if v_delivery.first_viewed_at is null then return false; end if;
    update public.broadcast_deliveries
       set clicked_at = coalesce(clicked_at, v_now), click_count = least(click_count + 1, 32767)
     where broadcast_id = p_broadcast_id and user_id = auth.uid();
  else
    if v_delivery.first_viewed_at is null then return false; end if;
    update public.broadcast_deliveries set dismissed_at = coalesce(dismissed_at, v_now)
     where broadcast_id = p_broadcast_id and user_id = auth.uid();
  end if;
  return true;
end;
$function$;
revoke all on function public.record_broadcast_delivery_event(bigint,text) from public, anon;
grant execute on function public.record_broadcast_delivery_event(bigint,text) to authenticated;

create or replace function public.member_active_broadcasts(p_client_platform text)
returns table (
  id bigint, kind text, title text, body text, button_label text, audience text,
  created_at timestamptz, expires_at timestamptz, options jsonb, target_ids jsonb,
  starts_at timestamptz, poke_at timestamptz, poke_count integer, poke_target_ids jsonb,
  image_url text, action_url text, action_label text, visual_style text,
  max_impressions smallint, repeat_interval_hours integer,
  delivery_view_count smallint, delivery_last_viewed_at timestamptz
)
language plpgsql stable security definer set search_path = ''
as $function$
begin
  if auth.uid() is null or coalesce(p_client_platform, '') not in ('mobile','web')
     or not exists (select 1 from public.profiles p where p.id = auth.uid() and p.joined = true) then
    raise exception 'joined member required' using errcode = '42501';
  end if;
  return query
  select b.id, b.kind, b.title, b.body, b.button_label, b.audience, b.created_at,
         b.expires_at, b.options, b.target_ids, b.starts_at, b.poke_at, b.poke_count,
         b.poke_target_ids, b.image_url, b.action_url, b.action_label, b.visual_style,
         b.max_impressions, b.repeat_interval_hours, d.view_count, d.last_viewed_at
    from public.admin_broadcasts b
    join public.broadcast_deliveries d on d.broadcast_id = b.id and d.user_id = auth.uid()
   where b.revoked = false
     and (b.expires_at is null or b.expires_at > pg_catalog.now())
     and (b.starts_at is null or b.starts_at <= pg_catalog.now())
     and (b.audience in ('all','selected')
       or (b.audience = 'app' and p_client_platform = 'mobile')
       or (b.audience = 'web' and p_client_platform = 'web'))
   order by b.created_at desc limit 10;
end;
$function$;
revoke all on function public.member_active_broadcasts(text) from public, anon;
grant execute on function public.member_active_broadcasts(text) to authenticated;

