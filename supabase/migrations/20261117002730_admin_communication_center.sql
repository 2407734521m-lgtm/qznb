-- Admin communication center: richer popups, recipient snapshots, delivery metrics and member groups.
alter table public.admin_broadcasts
  add column if not exists image_url text,
  add column if not exists action_url text,
  add column if not exists action_label text not null default '查看详情',
  add column if not exists visual_style text not null default 'standard',
  add column if not exists max_impressions smallint not null default 1,
  add column if not exists repeat_interval_hours integer not null default 24;

alter table public.admin_broadcasts
  add constraint admin_broadcasts_image_url_check
    check (image_url is null or (char_length(image_url) <= 1000 and image_url like 'https://%')),
  add constraint admin_broadcasts_action_url_check
    check (action_url is null or (char_length(action_url) <= 300 and left(action_url, 1) = '/' and left(action_url, 2) <> '//')),
  add constraint admin_broadcasts_action_label_check
    check (char_length(action_label) between 1 and 20),
  add constraint admin_broadcasts_visual_style_check
    check (visual_style = any (array['standard','highlight','compact']::text[])),
  add constraint admin_broadcasts_max_impressions_check
    check (max_impressions between 1 and 5),
  add constraint admin_broadcasts_repeat_interval_check
    check (repeat_interval_hours between 1 and 720);

create table if not exists public.admin_member_groups (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 40),
  description text not null default '' check (char_length(description) <= 200),
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists admin_member_groups_name_lower_uidx
  on public.admin_member_groups (lower(name));

create table if not exists public.admin_member_group_members (
  group_id bigint not null references public.admin_member_groups(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  added_at timestamptz not null default now(),
  primary key (group_id, user_id)
);
create index if not exists admin_member_group_members_user_idx
  on public.admin_member_group_members(user_id);

create table if not exists public.broadcast_deliveries (
  broadcast_id bigint not null references public.admin_broadcasts(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  first_viewed_at timestamptz,
  last_viewed_at timestamptz,
  view_count smallint not null default 0 check (view_count between 0 and 5),
  clicked_at timestamptz,
  click_count smallint not null default 0 check (click_count >= 0),
  dismissed_at timestamptz,
  primary key (broadcast_id, user_id)
);
create index if not exists broadcast_deliveries_user_idx
  on public.broadcast_deliveries(user_id, created_at desc);
create index if not exists broadcast_deliveries_broadcast_idx
  on public.broadcast_deliveries(broadcast_id, first_viewed_at);

alter table public.admin_member_groups enable row level security;
alter table public.admin_member_group_members enable row level security;
