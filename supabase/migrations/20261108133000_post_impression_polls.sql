-- Anonymous impression polls embedded in feed posts.
-- Voter identities are stored only to enforce one vote per member and are never
-- exposed through a table grant or RPC response.

begin;

create table if not exists public.post_impression_polls (
  post_id bigint primary key references public.posts(id) on delete cascade,
  author_id uuid not null references public.profiles(id) on delete cascade,
  question text not null check (char_length(btrim(question)) between 2 and 120),
  created_at timestamptz not null default now()
);

create table if not exists public.post_impression_options (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.post_impression_polls(post_id) on delete cascade,
  label text not null check (char_length(btrim(label)) between 1 and 40),
  position integer not null check (position between 1 and 8),
  unique (post_id, id)
);

create unique index if not exists post_impression_options_unique_label
  on public.post_impression_options (post_id, lower(btrim(label)));

create table if not exists public.post_impression_votes (
  post_id bigint not null references public.post_impression_polls(post_id) on delete cascade,
  option_id bigint not null,
  voter_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (post_id, voter_id),
  constraint post_impression_votes_option_fk
    foreign key (post_id, option_id)
    references public.post_impression_options(post_id, id)
    on delete cascade
);

create index if not exists post_impression_votes_option_idx
  on public.post_impression_votes (post_id, option_id);

alter table public.post_impression_polls enable row level security;
alter table public.post_impression_options enable row level security;
alter table public.post_impression_votes enable row level security;

-- Clients cannot read or write raw poll/vote rows. All access goes through
-- narrowly-scoped functions that only return aggregate counts.
revoke all on table public.post_impression_polls,
  public.post_impression_options,
  public.post_impression_votes
  from public, anon, authenticated;

create or replace function public.create_post_impression_poll(
  p_post_id bigint,
  p_question text,
  p_options text[]
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_actor uuid := auth.uid();
  v_question text := pg_catalog.btrim(coalesce(p_question, ''));
  v_label text;
  v_position integer := 0;
  v_option_count integer;
  v_distinct_count integer;
begin
  if v_actor is null
     or not public.is_member()
     or not public.member_moderation_allows('community')
     or not public.site_feature_enabled('posts') then
    raise exception 'not allowed to create an impression poll' using errcode = '42501';
  end if;

  if p_post_id is null
     or pg_catalog.char_length(v_question) < 2
     or pg_catalog.char_length(v_question) > 120
     or p_options is null
     or pg_catalog.cardinality(p_options) < 2
     or pg_catalog.cardinality(p_options) > 8 then
    raise exception 'invalid impression poll' using errcode = '22023';
  end if;

  select pg_catalog.count(*),
         pg_catalog.count(distinct pg_catalog.lower(pg_catalog.btrim(option_value)))
    into v_option_count, v_distinct_count
  from pg_catalog.unnest(p_options) as options(option_value)
  where pg_catalog.btrim(option_value) <> ''
    and pg_catalog.char_length(pg_catalog.btrim(option_value)) <= 40;

  if v_option_count <> pg_catalog.cardinality(p_options)
     or v_distinct_count <> v_option_count then
    raise exception 'poll options must be unique and contain 1–40 characters' using errcode = '22023';
  end if;

  if not exists (
    select 1
    from public.posts p
    where p.id = p_post_id
      and p.author_id = v_actor
      and p.section = 'feed'
      and p.deleted_at is null
  ) then
    raise exception 'post not found or not owned by caller' using errcode = '42501';
  end if;

  insert into public.post_impression_polls (post_id, author_id, question)
  values (p_post_id, v_actor, v_question);

  foreach v_label in array p_options loop
    v_position := v_position + 1;
    insert into public.post_impression_options (post_id, label, position)
    values (p_post_id, pg_catalog.btrim(v_label), v_position);
  end loop;

  return true;
end;
$function$;

create or replace function public.get_post_impression_poll_results(p_post_ids bigint[])
returns table (
  post_id bigint,
  question text,
  option_id bigint,
  option_label text,
  option_position integer,
  vote_count bigint,
  total_votes bigint,
  my_option_id bigint
)
language plpgsql
stable
security definer
set search_path = ''
as $function$
declare
  v_actor uuid := auth.uid();
begin
  if v_actor is null or not public.is_member() then
    raise exception 'member access required' using errcode = '42501';
  end if;

  return query
  select
    poll.post_id,
    poll.question,
    opt.id,
    opt.label,
    opt.position,
    pg_catalog.count(vote.voter_id)::bigint,
    (
      select pg_catalog.count(*)::bigint
      from public.post_impression_votes all_votes
      where all_votes.post_id = poll.post_id
    ),
    (
      select own_vote.option_id
      from public.post_impression_votes own_vote
      where own_vote.post_id = poll.post_id
        and own_vote.voter_id = v_actor
    )
  from public.post_impression_polls poll
  join public.posts post on post.id = poll.post_id
  join public.post_impression_options opt on opt.post_id = poll.post_id
  left join public.post_impression_votes vote
    on vote.post_id = poll.post_id and vote.option_id = opt.id
  where post.section = 'feed'
    and post.deleted_at is null
    and (p_post_ids is null or poll.post_id = any(p_post_ids))
  group by poll.post_id, poll.question, opt.id, opt.label, opt.position
  order by poll.post_id, opt.position;
end;
$function$;

create or replace function public.cast_post_impression_vote(
  p_post_id bigint,
  p_option_id bigint
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_actor uuid := auth.uid();
  v_poll_post_id bigint;
begin
  if v_actor is null
     or not public.is_member()
     or not public.member_moderation_allows('community') then
    raise exception 'member voting access required' using errcode = '42501';
  end if;

  select poll.post_id
    into v_poll_post_id
  from public.post_impression_polls poll
  join public.posts post on post.id = poll.post_id
  join public.post_impression_options opt on opt.post_id = poll.post_id
  where poll.post_id = p_post_id
    and opt.id = p_option_id
    and post.section = 'feed'
    and post.deleted_at is null
    and post.author_id <> v_actor
  for update of poll;

  if v_poll_post_id is null then
    raise exception 'poll or option not found' using errcode = 'P0002';
  end if;

  insert into public.post_impression_votes (post_id, option_id, voter_id)
  values (v_poll_post_id, p_option_id, v_actor)
  on conflict (post_id, voter_id)
  do update set option_id = excluded.option_id, created_at = now();

  return true;
end;
$function$;

revoke all on function public.create_post_impression_poll(bigint, text, text[]) from public, anon;
grant execute on function public.create_post_impression_poll(bigint, text, text[]) to authenticated;

revoke all on function public.get_post_impression_poll_results(bigint[]) from public, anon;
grant execute on function public.get_post_impression_poll_results(bigint[]) to authenticated;

revoke all on function public.cast_post_impression_vote(bigint, bigint) from public, anon;
grant execute on function public.cast_post_impression_vote(bigint, bigint) to authenticated;

commit;
