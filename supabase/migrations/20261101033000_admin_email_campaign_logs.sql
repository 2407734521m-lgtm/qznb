-- Private email campaign audit. Recipient emails and message bodies are never stored.

begin;

create table if not exists public.admin_email_campaigns (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id) on delete set null,
  subject text not null check (char_length(subject) between 1 and 160),
  selected_count integer not null check (selected_count between 1 and 100),
  sent_count integer not null default 0 check (sent_count >= 0),
  failed_count integer not null default 0 check (failed_count >= 0),
  check (sent_count + failed_count <= selected_count),
  status text not null default 'processing' check (status in ('processing', 'completed', 'partial', 'failed')),
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

create table if not exists public.admin_email_campaign_recipients (
  id bigint generated by default as identity primary key,
  campaign_id bigint not null references public.admin_email_campaigns(id) on delete cascade,
  profile_id uuid references public.profiles(id) on delete set null,
  status text not null check (status in ('queued', 'sent', 'failed', 'no_email')),
  provider_message_id text,
  error_code text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (campaign_id, profile_id)
);

create index if not exists admin_email_campaigns_recent_idx
  on public.admin_email_campaigns(created_at desc);
create index if not exists admin_email_campaign_recipients_campaign_idx
  on public.admin_email_campaign_recipients(campaign_id, status);

alter table public.admin_email_campaigns enable row level security;
alter table public.admin_email_campaign_recipients enable row level security;
revoke all on table public.admin_email_campaigns from public, anon, authenticated;
revoke all on table public.admin_email_campaign_recipients from public, anon, authenticated;
grant all on table public.admin_email_campaigns to service_role;
grant all on table public.admin_email_campaign_recipients to service_role;
grant usage, select on sequence public.admin_email_campaigns_id_seq to service_role;
grant usage, select on sequence public.admin_email_campaign_recipients_id_seq to service_role;

create or replace function public.admin_email_campaign_history()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_result jsonb;
begin
  if auth.uid() is null or coalesce(public.my_role(), '') not in ('admin', 'super_admin') then
    raise exception 'administrator required' using errcode = '42501';
  end if;

  select coalesce(
    pg_catalog.jsonb_agg(
      pg_catalog.jsonb_build_object(
        'id', c.id,
        'subject', c.subject,
        'selected_count', c.selected_count,
        'sent_count', c.sent_count,
        'failed_count', c.failed_count,
        'status', c.status,
        'created_at', c.created_at,
        'completed_at', c.completed_at,
        'actor_name', coalesce(nullif(p.display_name, ''), p.username, '管理员'),
        'no_email_count', (
          select count(*) from public.admin_email_campaign_recipients r
          where r.campaign_id = c.id and r.status = 'no_email'
        ),
        'provider_failure_count', (
          select count(*) from public.admin_email_campaign_recipients r
          where r.campaign_id = c.id and r.status = 'failed'
        )
      ) order by c.created_at desc
    ),
    '[]'::jsonb
  )
  into v_result
  from (
    select * from public.admin_email_campaigns
    order by created_at desc
    limit 30
  ) c
  left join public.profiles p on p.id = c.actor_id;

  return v_result;
end;
$function$;

revoke all on function public.admin_email_campaign_history() from public, anon;
grant execute on function public.admin_email_campaign_history() to authenticated;

commit;
